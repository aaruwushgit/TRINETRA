@_rest.get("/dataset/samples/{key}")
def download_dataset_sample(key: str):
    """
    Download a ready-made demo dataset in the exact format /jobs/dataset accepts.

    Serving these from the API rather than shipping them in the page keeps one
    copy on disk: the same file a demonstrator uploads is the file the
    generator wrote, so "it validated for me" means something.
    """
    spec = _SAMPLE_DATASETS.get(key)
    if spec is None:
        raise HTTPException(
            status_code=404,
            detail=f"Unknown sample '{key}'. Available: {', '.join(_SAMPLE_DATASETS)}.",
        )
    path = _sample_path(key)
    if path is None:
        raise HTTPException(
            status_code=404,
            detail=(
                f"{spec['label']} has not been generated on this server yet. "
                f"Run: {spec['regenerate']}"
            ),
        )
    return FileResponse(path, media_type=spec["media_type"], filename=spec["filename"])


@_rest.post("/dataset/validate")
async def validate_dataset(
    file: UploadFile = File(...),
    kind: str = Form(default="auto"),
):
    """
    Parse and validate a dataset without writing anything, anywhere.

    Returns the same per-row error list (`artefact`, `row`, `msg`) the browser
    produces, so a client can show one error widget regardless of which side
    caught the problem.
    """
    parsed = await _read_and_parse_dataset(file, kind)
    summary = parsed.summary()
    summary["warnings"] = summary["warnings"] + await _threaded(_reference_warnings, parsed)
    summary["ingestable"] = not parsed.errors and parsed.rows_parsed > 0
    return summary


@_rest.post("/dataset", status_code=201)
async def ingest_dataset(
    file: UploadFile = File(...),
    kind: str = Form(default="auto"),
    sandbox: bool = Form(default=True),
    deployment: str | None = Form(default=None),
):
    """
    Ingest a city dataset (cameras and/or events) — JSON or CSV.

    `sandbox` defaults to **true**: the rows land in a throwaway database file
    with the production schema, so a stranger's upload can exercise the real
    pipeline without being able to overwrite the live city's cameras. Pass
    `sandbox=false` to load into the operational database.

    A dataset with any row error is refused as a whole (422) rather than
    partially loaded — half a city is worse than none, because every downstream
    trajectory would then be silently missing hops.
    """
    parsed = await _read_and_parse_dataset(file, kind)

    if parsed.errors:
        summary = parsed.summary()
        summary["warnings"] = summary["warnings"] + await _threaded(_reference_warnings, parsed)
        raise HTTPException(
            status_code=422,
            detail={
                "message": (
                    f"{len(parsed.errors)} row(s) do not match the contract; nothing "
                    f"was ingested. See GET /jobs/dataset/schema for the field list."
                ),
                **summary,
            },
        )
    if parsed.rows_parsed == 0:
        raise HTTPException(
            status_code=422,
            detail="The file parsed cleanly but contained no camera or event rows.",
        )

    try:
        result = await _threaded(
            dataset_service.ingest, parsed, sandbox=sandbox, deployment=deployment
        )
    except HTTPException:
        raise
    except Exception as exc:  # noqa: BLE001 — surface a sentence, log the trace
        raise HTTPException(
            status_code=500,
            detail=f"Ingestion failed: {type(exc).__name__}: {exc}",
        ) from exc

    result["warnings"] = await _threaded(_reference_warnings, parsed)
    return result


async def _threaded(fn, *args, **kwargs):
    """Run blocking work off the event loop.

    These handlers are `async def` because reading a multipart upload in chunks
    needs `await`. That makes everything else in them run *on the event loop* —
    and dataset ingestion is a long synchronous stretch of SQLite writes. Called
    directly, a 31k-row upload blocks every other request for its whole
    duration, and if it stalls on a write lock (the simulation clock holds one
    every half second) the entire API stops answering, not just this request.

    `asyncio.to_thread` puts it back where blocking work belongs.
    """
    import functools

    return await asyncio.to_thread(functools.partial(fn, *args, **kwargs))


async def _read_and_parse_dataset(file: UploadFile, kind: str):
    """Shared body of the validate and ingest handlers."""
    if kind not in ("auto", "cameras", "events"):
        raise HTTPException(
            status_code=400,
            detail=f"kind must be 'auto', 'cameras' or 'events', not {kind!r}.",
        )

    # Read in chunks against the cap rather than file.read(): an unbounded read
    # of a hostile upload is a memory-exhaustion primitive.
    limit = dataset_service.MAX_UPLOAD_BYTES
    buffer = bytearray()
    while True:
        chunk = await file.read(CHUNK)
        if not chunk:
            break
        buffer.extend(chunk)
        if len(buffer) > limit:
            raise HTTPException(
                status_code=413,
                detail=f"Dataset exceeds the {limit // (1024 * 1024)} MB limit.",
            )
    if not buffer:
        raise HTTPException(status_code=400, detail="Uploaded file is empty.")

    try:
        return dataset_service.parse_dataset(bytes(buffer), file.filename, kind)
    except ValueError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc


def _reference_warnings(parsed) -> list[str]:
    """Flag events whose camera_id is defined neither in the file nor in the DB."""
    if not parsed.events:
        return []
    try:
        from backend.database import SessionLocal
        from backend.models.camera import Camera

        session = SessionLocal()
        try:
            dataset_service._set_busy_timeout(session)
            referenced = sorted({e["camera_id"] for e in parsed.events})
            known: set[str] = set()
            for start in range(0, len(referenced), 500):
                chunk = referenced[start:start + 500]
                known |= {
                    row[0] for row in
                    session.query(Camera.camera_id).filter(Camera.camera_id.in_(chunk)).all()
                }
        finally:
            session.close()
    except Exception:
        known = set()
    return dataset_service.check_references(parsed, known)


