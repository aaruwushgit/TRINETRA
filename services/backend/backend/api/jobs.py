"""
Jobs router — upload media, get plates in the database.

This is the endpoint the demo drives: a video goes in, a job id comes back
immediately, a WebSocket streams progress while the pipeline runs, and the
plates land in `vehicle_events` for the same camera the operator picked.

Two things worth explaining:

**`source_path` exists so the demo does not have to upload 180 MB.** The test
footage already sits on the machine running the API. Re-uploading it through
multipart to process it would add minutes to a live demo for no benefit, so a
path can be passed instead — restricted to a small allowlist of directories,
because an unrestricted server-side path parameter is a file-read primitive
handed to whoever can reach the API.

**Nothing here returns a traceback.** Every handler maps failures onto an
HTTPException with a sentence an operator can act on. The traceback still goes
to the server log, where it is useful.
"""
