def _sample_path(key: str) -> Path | None:
    """Resolve a sample to a real file, or None if it has not been generated."""
    spec = _SAMPLE_DATASETS.get(key)
    if spec is None:
        return None
    path = (_DEPLOYMENTS_DIR / spec["relative"]).resolve()
    # Confine to deployments/ even though `key` comes from a fixed dict: the
    # check costs nothing and survives someone later making the key dynamic.
    try:
        path.relative_to(_DEPLOYMENTS_DIR.resolve())
    except ValueError:
        return None
    return path if path.is_file() else None


# ── helpers ──────────────────────────────────────────────────────────────────

def _safe_suffix(filename: str | None, allowed: set[str], what: str) -> str:
    suffix = Path(filename or "").suffix.lower()
    if suffix not in allowed:
        raise HTTPException(
            status_code=400,
            detail=(
                f"Unsupported {what} format '{suffix or filename or 'unknown'}'. "
                f"Allowed: {', '.join(sorted(allowed))}"
            ),
        )
    return suffix


async def _save_upload(file: UploadFile, allowed: set[str], max_bytes: int, what: str) -> Path:
    """Stream an upload to disk, enforcing the size cap as it goes."""
    suffix = _safe_suffix(file.filename, allowed, what)

    video_job_service.UPLOAD_DIR.mkdir(parents=True, exist_ok=True)
    # The client's filename is kept for readability but sanitized and prefixed
    # with a uuid, so two uploads of "video.mp4" cannot overwrite each other and
    # a crafted name cannot escape the upload directory.
    stem = _SAFE_NAME.sub("_", Path(file.filename or "upload").stem)[:60] or "upload"
    target = video_job_service.UPLOAD_DIR / f"{uuid.uuid4().hex[:12]}_{stem}{suffix}"

    written = 0
    try:
        with target.open("wb") as out:
            while True:
                chunk = await file.read(CHUNK)
                if not chunk:
                    break
                written += len(chunk)
                if written > max_bytes:
                    raise HTTPException(
                        status_code=413,
                        detail=(
                            f"{what.capitalize()} exceeds the "
                            f"{max_bytes // (1024 * 1024)} MB limit. "
                            "Pass source_path instead to process a file already on the server."
                        ),
                    )
                out.write(chunk)
    except HTTPException:
        target.unlink(missing_ok=True)
        raise
    except Exception as exc:
        target.unlink(missing_ok=True)
        raise HTTPException(status_code=500, detail=f"Could not save upload: {exc}") from exc

    if written == 0:
        target.unlink(missing_ok=True)
        raise HTTPException(status_code=400, detail="Uploaded file is empty.")

    return target


def _resolve_source_path(source_path: str, allowed: set[str], what: str) -> Path:
    """Validate a server-side path against the allowlist."""
    try:
        path = Path(source_path).expanduser().resolve(strict=True)
    except (OSError, RuntimeError):
        raise HTTPException(status_code=400, detail=f"source_path not found: {source_path}") from None

    if not path.is_file():
        raise HTTPException(status_code=400, detail=f"source_path is not a file: {path}")

    roots = [r.resolve() for r in ALLOWED_SOURCE_ROOTS if r.exists()]
    if not any(path.is_relative_to(root) for root in roots):
        raise HTTPException(
            status_code=403,
            detail=(
                "source_path must live under an allowed directory: "
                + ", ".join(str(r) for r in roots)
            ),
        )

    if path.suffix.lower() not in allowed:
        raise HTTPException(
            status_code=400,
            detail=f"Unsupported {what} format '{path.suffix}'. Allowed: {', '.join(sorted(allowed))}",
        )
    return path


def _submit_or_400(fn, **kwargs) -> str:
    """Turn the job runner's validation errors into clean 4xx responses."""
    try:
        return fn(**kwargs)
    except FileNotFoundError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    except (ValueError, KeyError) as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    except Exception as exc:  # model load failure, bad weights path, ...
        raise HTTPException(
            status_code=500, detail=f"Could not start job: {type(exc).__name__}: {exc}"
        ) from exc


