# A second, unprefixed router: the frontend groups every WebSocket under /ws,
# and an APIRouter prefix applies to websocket routes too, so /jobs + /ws
# cannot come from one router. Both are combined into `router` at the bottom so
# backend/main.py still needs exactly one include_router call.
_ws = APIRouter(tags=["Jobs"])


@_ws.websocket("/ws/jobs/{job_id}")
async def stream_job(websocket: WebSocket, job_id: str):
    """Push the job status ~2x/second until it reaches a terminal state.

    Closes itself once the job finishes rather than idling forever: a dashboard
    that leaves a socket open per completed upload accumulates them for the
    length of the demo.
    """
    await websocket.accept()

    job = video_job_service.get_job(job_id)
    if job is None:
        # Accept first, then report — a client that gets a bare handshake
        # rejection has no way to show the user why.
        try:
            await websocket.send_json({"error": f"Job '{job_id}' not found."})
            await websocket.close(code=1008)
        except Exception:
            pass
        return

    try:
        while True:
            job = video_job_service.get_job(job_id)
            if job is None:
                await websocket.send_json({"error": "Job record was evicted."})
                break

            await websocket.send_json(job)
            if job["state"] in TERMINAL_STATES:
                break
            await asyncio.sleep(0.5)
    except (WebSocketDisconnect, asyncio.CancelledError):
        # Normal: the operator navigated away mid-run. Not an error, and it
        # must not take the job down with it.
        return
    except Exception:
        return
    finally:
        try:
            await websocket.close()
        except Exception:
            pass


