_rest = APIRouter(prefix="/jobs", tags=["Jobs"])

VIDEO_EXTENSIONS = {".mp4", ".mov", ".avi", ".mkv", ".m4v", ".webm", ".mpg", ".mpeg"}
IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".bmp", ".webp", ".tif", ".tiff"}

# 512 MB. The largest piece of test footage is 180 MB, and a cap exists so a
# malformed or hostile upload cannot fill the disk that the SQLite database
# lives on.
MAX_VIDEO_BYTES = 512 * 1024 * 1024
MAX_IMAGE_BYTES = 32 * 1024 * 1024

# Read the upload in chunks rather than `await file.read()`: a single read
# materializes the whole 180 MB video in RAM before a single byte is written.
CHUNK = 4 * 1024 * 1024

# Directories a client may reference by path. Anything outside these is
# refused, so `source_path` cannot be used to read /etc/passwd or a .env file.
ALLOWED_SOURCE_ROOTS = [
    video_job_service.UPLOAD_DIR,
    Path("/Users/aarushsharma/Documents/SIH/archive"),
    Path("/Users/aarushsharma/Documents/SIH/services/alpr"),
]

_SAFE_NAME = re.compile(r"[^A-Za-z0-9._-]+")

