@_rest.post("/video", status_code=202)
async def create_video_job(
    camera_id: str = Form(...),
    file: UploadFile | None = File(default=None),
    source_path: str | None = Form(default=None),
    ocr_every: int = Form(default=3),
    min_reads: int = Form(default=2),
    max_frames: int | None = Form(default=None),
    region: str | None = Form(default=None),
    sandbox: bool = Form(default=False),
):
    """
    Submit a video for plate detection + database ingestion.

    Provide either a multipart `file` upload, or `source_path` pointing at a
    video already on the server (much faster for large local footage).
    Returns 202 with a job id — poll GET /jobs/{job_id} or subscribe to
    WS /ws/jobs/{job_id}.
    """
    if file is None and not source_path:
        raise HTTPException(
            status_code=400, detail="Provide either a 'file' upload or a 'source_path'."
        )
    if file is not None and source_path:
        raise HTTPException(
            status_code=400, detail="Provide 'file' or 'source_path', not both."
        )

    if source_path:
        path = _resolve_source_path(source_path, VIDEO_EXTENSIONS, "video")
    else:
        path = await _save_upload(file, VIDEO_EXTENSIONS, MAX_VIDEO_BYTES, "video")

    job_id = _submit_or_400(
        video_job_service.submit_video_job,
        file_path=path,
        camera_id=camera_id,
        ocr_every=ocr_every,
        min_reads=min_reads,
        max_frames=max_frames,
        region=region,
        sandbox=sandbox,
    )
    return {
        "job_id": job_id,
        "state": "QUEUED",
        "camera_id": camera_id,
        "source": path.name,
        "sandbox": sandbox,
        "poll": f"/jobs/{job_id}",
        "stream": f"/ws/jobs/{job_id}",
    }


