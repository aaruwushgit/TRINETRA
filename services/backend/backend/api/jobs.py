@_rest.get("/{job_id}")
def read_job(job_id: str):
    """Full status: progress, live counters, pipeline stats, compute summary."""
    job = video_job_service.get_job(job_id)
    if job is None:
        raise HTTPException(
            status_code=404,
            detail=f"Job '{job_id}' not found. Only the last "
            f"{video_job_service.MAX_JOBS} jobs are retained.",
        )
    return job


@_rest.get("/{job_id}/plates")
def read_job_plates(job_id: str):
    """The plates this job found — final rows, plus in-progress votes if running."""
    plates = video_job_service.get_job_plates(job_id)
    if plates is None:
        raise HTTPException(status_code=404, detail=f"Job '{job_id}' not found.")
    return plates


@_rest.get("/{job_id}/events")
def read_job_events(job_id: str, limit: int = 200):
    """Events a *sandbox* job wrote, read back from its isolated database.

    Non-sandbox jobs write into the main tables, so their events are already
    visible through /events/recent and are not duplicated here.
    """
    job = video_job_service.get_job(job_id)
    if job is None:
        raise HTTPException(status_code=404, detail=f"Job '{job_id}' not found.")
    if not job.get("sandbox"):
        raise HTTPException(
            status_code=400,
            detail="This job wrote to the main database — use GET /events/recent instead.",
        )
    limit = max(1, min(limit, 1000))
    return {
        "job_id": job_id,
        "events": video_job_service.sandbox_events(job_id, limit=limit),
    }


@_rest.post("/{job_id}/cancel")
def cancel_job(job_id: str):
    """Stop a running job at the next frame; plates read so far are kept."""
    if video_job_service.get_job(job_id) is None:
        raise HTTPException(status_code=404, detail=f"Job '{job_id}' not found.")
    if not video_job_service.cancel_job(job_id):
        raise HTTPException(status_code=409, detail="Job has already finished.")
    return {"job_id": job_id, "cancelling": True}


